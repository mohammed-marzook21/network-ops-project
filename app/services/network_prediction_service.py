"""
Real ML prediction service for API5.

Phase 6 ML5, Network Operations Predictive Intelligence Project.

Loads the trained ML3 classifier and serves predictions while preserving
the existing API5 consumer contract.
"""

from pathlib import Path

import joblib
import pandas as pd


MODEL_PATH = (
    Path(__file__).resolve().parents[2]
    / "models"
    / "network_risk_model.joblib"
)

EXPECTED_FEATURES = [
    "avg_activity",
    "activity_growth",
    "active_hours",
    "peak_ratio",
    "variability",
    "internet_share",
]


def load_model_artifact():
    """
    Load and validate the trained ML3 model artifact.

    Fail clearly rather than silently falling back to the Phase 4 stub.
    """

    if not MODEL_PATH.exists():
        raise RuntimeError(
            "Network risk model artifact is missing: "
            f"{MODEL_PATH}. "
            "Run ML3 training before starting the API."
        )

    try:
        artifact = joblib.load(MODEL_PATH)
    except Exception as exc:
        raise RuntimeError(
            "Network risk model artifact could not be loaded: "
            f"{MODEL_PATH}"
        ) from exc

    if not isinstance(artifact, dict):
        raise RuntimeError(
            "Network risk model artifact has an invalid format."
        )

    required_keys = {
        "model",
        "feature_names",
        "model_version",
    }

    missing_keys = required_keys - artifact.keys()

    if missing_keys:
        raise RuntimeError(
            "Network risk model artifact is missing required metadata: "
            + ", ".join(sorted(missing_keys))
        )

    feature_names = list(artifact["feature_names"])

    if feature_names != EXPECTED_FEATURES:
        raise RuntimeError(
            "Model feature schema does not match API5/ML2 schema. "
            f"Expected {EXPECTED_FEATURES}, got {feature_names}."
        )

    return artifact


MODEL_ARTIFACT = load_model_artifact()
MODEL = MODEL_ARTIFACT["model"]
MODEL_VERSION = MODEL_ARTIFACT["model_version"]
MODEL_FEATURES = list(MODEL_ARTIFACT["feature_names"])


def classify_risk_level(risk_score: float) -> str:
    """
    Convert model probability into an operational attention level.

    These are attention categories, not confirmed network-fault states.
    """

    if risk_score >= 0.70:
        return "high"

    if risk_score >= 0.30:
        return "medium"

    return "low"


def predict_network_risk(prediction_input):
    """
    Generate a real risk prediction from the trained ML3 classifier.
    """

    values = {
        feature: getattr(prediction_input, feature)
        for feature in MODEL_FEATURES
    }

    feature_frame = pd.DataFrame(
        [values],
        columns=MODEL_FEATURES,
    )

    risk_score = float(
        MODEL.predict_proba(feature_frame)[0, 1]
    )

    risk_level = classify_risk_level(risk_score)

    return {
        "risk_score": risk_score,
        "risk_level": risk_level,
        "model_version": MODEL_VERSION,
        "feature_timestamp": None,
        "explanation_note": (
            "Risk score generated by the trained ML3 logistic-regression "
            "classifier from the six ML2 network activity features. "
            "The result is an investigation signal and does not confirm "
            "congestion, outage, capacity exhaustion, or service degradation."
        ),
    }